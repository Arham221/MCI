/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_RTC_Init();

  /* USER CODE BEGIN 2 */
  // Initialize GPIO peripherals using direct register access
  GPIO_Init_RegisterLevel();
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    // Part 1A: Polling Switch PA0 using Input Data Register (IDR)
    if (GPIOA->IDR & (1U << 0)) 
    {
        // Switch pressed (HIGH): Set Output Data Register (ODR) bit 8 -> Turn ON PE8 LED
        GPIOE->ODR |= (1U << 8);
    } 
    else 
    {
        // Switch released (LOW): Clear ODR bit 8 -> Turn OFF PE8 LED
        GPIOE->ODR &= ~(1U << 8);
    }
  }
  /* USER CODE END 3 */
}

