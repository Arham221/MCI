/* USER CODE BEGIN 0 */
void GPIO_Init_RegisterLevel(void)
{
    // 1. Enable AHB peripheral clocks for GPIOA (User Switch) and GPIOE (LEDs)
    RCC->AHBENR |= (1U << 17); // GPIOA clock enable
    RCC->AHBENR |= (1U << 21); // GPIOE clock enable

    // 2. Configure PA0 (User Switch) as Input (MODER0 = 00)
    GPIOA->MODER &= ~(3U << (0 * 2));

    // 3. Configure PE8 (User LED) as Output (MODER8 = 01)
    GPIOE->MODER &= ~(3U << (8 * 2)); // Clear bits
    GPIOE->MODER |=  (1U << (8 * 2)); // Set bit 0 -> Output mode
}
